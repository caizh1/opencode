  test("keeps daily usage month labels on the same week columns as the heatmap", () => {
    const dayMs = 24 * 60 * 60 * 1000
    const startOfDay = (value: string | number) => {
      const date = new Date(value)
      date.setHours(0, 0, 0, 0)
      return date.getTime()
    }
    const startOfMondayWeek = (value: string | number) => {
      const start = startOfDay(value)
      const day = new Date(start).getDay()
      return start - (day === 0 ? 6 : day - 1) * dayMs
    }
    const weekColumn = (value: string | number, calendarStart: number) => Math.max(0, Math.floor((startOfMondayWeek(value) - calendarStart) / (dayMs * 7)))

    const calendarStart = startOfMondayWeek("2025-06-27T00:00:00")
    const march25Column = weekColumn("2026-03-25T00:00:00", calendarStart)
    const mayColumn = weekColumn("2026-05-01T00:00:00", calendarStart)
    const juneColumn = weekColumn("2026-06-01T00:00:00", calendarStart)

    expect(march25Column).toBeLessThan(mayColumn)
    expect(march25Column).toBeLessThan(juneColumn)
  })

